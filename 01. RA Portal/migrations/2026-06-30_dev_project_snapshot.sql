create or replace view public.dev_project_34_summary as
select
    dpl.list_no,
    dpl.dev_project_id,
    dpl.source_category,
    dpl.project_name,
    dpl.vehicle_text,
    dpl.inclusion_basis,
    dpl.review_note,
    coalesce(projects.project_count, 0) as linked_project_count,
    coalesce(funds.fund_count, 0) as linked_fund_count,
    coalesce(assets.asset_count, 0) as linked_asset_count,
    projects.project_ids,
    projects.project_names,
    funds.fund_ids,
    funds.short_names,
    funds.fund_names,
    assets.asset_ids,
    assets.asset_names
from public.dev_project_list dpl
left join lateral (
    select
        count(*) as project_count,
        array_agg(dppl.project_id order by dppl.is_primary desc, dppl.project_id) as project_ids,
        array_agg(dppl.project_name_snapshot order by dppl.is_primary desc, dppl.project_id) as project_names
    from public.dev_project_project_links dppl
    where dppl.dev_project_id = dpl.dev_project_id
) projects on true
left join lateral (
    select
        count(*) as fund_count,
        array_agg(dpfl.fund_id order by dpfl.is_primary desc, dpfl.fund_id) as fund_ids,
        array_agg(dpfl.short_name_snapshot order by dpfl.is_primary desc, dpfl.fund_id) as short_names,
        array_agg(dpfl.fund_name_snapshot order by dpfl.is_primary desc, dpfl.fund_id) as fund_names
    from public.dev_project_fund_links dpfl
    where dpfl.dev_project_id = dpl.dev_project_id
) funds on true
left join lateral (
    select
        count(distinct dpal.asset_id) as asset_count,
        array_agg(distinct dpal.asset_id) as asset_ids,
        array_agg(distinct dpal.canonical_name_snapshot) as asset_names
    from public.dev_project_asset_links dpal
    where dpal.dev_project_id = dpl.dev_project_id
) assets on true;

