-- Development project 34-list snapshot for RA dashboard.
--
-- Purpose:
-- - Keep the 2026-06-30 development-project draft list in the same Supabase DB.
-- - Do not copy source project/fund/asset master rows.
-- - Store only a thin list plus links back to existing public.projects,
--   public.funds, and public.asset_master rows.
--
-- How to run:
-- - Paste this full file into Supabase SQL Editor and run once.
-- - The script is idempotent for the 2026-06-30 seed.

