create table if not exists public.dev_project_extract_snapshots (
    snapshot_id text primary key,
    snapshot_date date not null,
    source_thread_id text,
    source_label text not null,
    source_asof_date date not null,
    list_count integer not null,
    extractor_version text not null default 'manual_sql_seed_v1',
    notes text,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.dev_project_list (
    dev_project_id text primary key,
    list_no integer not null unique,
    source_category text not null check (source_category in ('PFV', 'Fund')),
    project_name text not null,
    vehicle_text text,
    inclusion_basis text not null,
    source_snapshot_id text not null references public.dev_project_extract_snapshots(snapshot_id) on delete restrict,
    source_thread_id text not null,
    source_asof_date date not null,
    match_status text not null default 'seeded',
    review_note text,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.dev_project_project_links (
    dev_project_id text not null references public.dev_project_list(dev_project_id) on delete cascade,
    project_id text not null references public.projects(project_id) on delete restrict,
    project_name_snapshot text,
    relation_role text not null default 'primary_project',
    is_primary boolean not null default true,
    match_method text not null,
    match_confidence numeric(4, 2) not null check (match_confidence >= 0 and match_confidence <= 1),
    notes text,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    primary key (dev_project_id, project_id)
);

create table if not exists public.dev_project_fund_links (
    dev_project_id text not null references public.dev_project_list(dev_project_id) on delete cascade,
    fund_id text not null references public.funds(fund_id) on delete restrict,
    short_name_snapshot text,
    fund_name_snapshot text,
    vehicle_role text not null default 'primary_vehicle',
    is_primary boolean not null default true,
    match_method text not null,
    match_confidence numeric(4, 2) not null check (match_confidence >= 0 and match_confidence <= 1),
    notes text,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    primary key (dev_project_id, fund_id)
);

create table if not exists public.dev_project_asset_links (
    link_id bigint generated by default as identity primary key,
    dev_project_id text not null references public.dev_project_list(dev_project_id) on delete cascade,
    asset_id text not null references public.asset_master(asset_id) on delete restrict,
    canonical_name_snapshot text,
    asset_role text not null default 'related_asset',
    is_primary boolean not null default false,
    link_source text not null,
    link_source_id text not null,
    match_method text not null,
    match_confidence numeric(4, 2) not null check (match_confidence >= 0 and match_confidence <= 1),
    notes text,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create unique index if not exists dev_project_asset_links_unique_source
    on public.dev_project_asset_links(dev_project_id, asset_id, link_source, link_source_id);

create index if not exists dev_project_list_category_idx
    on public.dev_project_list(source_category, list_no);
create index if not exists dev_project_project_links_project_idx
    on public.dev_project_project_links(project_id);
create index if not exists dev_project_fund_links_fund_idx
    on public.dev_project_fund_links(fund_id);
create index if not exists dev_project_asset_links_asset_idx
    on public.dev_project_asset_links(asset_id);

